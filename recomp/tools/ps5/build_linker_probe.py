"""Cross-build/package separate synthetic console linker/compiler tests; never deploy.

Create the foundation with PS5_VulkanTemplate/ps5/tools/new-title.py first.
`prepare` builds only probe/foundation objects; `package` requires finished native
LLD (or full Clang) archives. Neither phase executes compiled test code on the
development PC.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from builder.core import Builder, BuildError, sha, verify_kit, verify_native_elf
from build_console_compiler import run

TITLE_ID = 'PPSA99146'
SAMPLE = 'sims2linkerdiagnostics'


def prepare(a, settings):
    foundation = a.foundation.resolve()
    param = json.loads((foundation/'ps5/sce_sys/param.json').read_text())
    if param['titleId'] != TITLE_ID:
        raise BuildError('Refusing to modify a different title')
    if not (foundation/'examples'/SAMPLE).is_dir():
        raise BuildError('Create the diagnostic foundation with new-title.py first')
    compiler = ROOT/'compiler'
    native_info = None
    inputs = ['console_probe.cpp', 'console_probe.h', 'console_probe_app.cpp',
              'link_fixture.cpp', 'linker.cpp', 'worker.cpp', 'worker.h', 'fatal.cpp',
              'fatal.h', 'embedded.h', 'ps5-toolchain.cmake', 'CMakeLists.txt',
              'ps5-support-config.h', 'ps5-link-bindings.json',
              'console_compile_steps.inc', 'compile_fixture.cpp']
    if a.mode == 'compiler': inputs.append('embedded.cpp')
    if a.execute:
        inputs += ['console_execute_steps.inc', 'probe_core_loader.cpp', 'probe_core_loader.h',
                   'probe_oracle.h', 'third_party/ps5_retroarch/core_loader_ps5.cpp',
                   'third_party/ps5_retroarch/ps5-core.ld', 'third_party/ps5_retroarch/ORIGIN.json']
        origin = json.loads((compiler/'third_party/ps5_retroarch/ORIGIN.json').read_text())
        for local, upstream in [('core_loader_ps5.cpp', 'src/core_loader_ps5.cpp'),
                                ('ps5-core.ld', 'tooling/native/ps5-core.ld')]:
            if sha(compiler/'third_party/ps5_retroarch'/local) != origin['files'][upstream]['sha256']:
                raise BuildError('Pinned upstream loader changed: '+local)
    if a.generate:
        inputs += ['console_generate_steps.inc', 'generator.h', 'generator.cpp',
                   '../sdk/tools/recomp/main.cpp', '../sdk/tools/recomp/ps5_filesystem.h']
        a.output.resolve().mkdir(parents=True, exist_ok=True)
        # Recheck only the actual native generator target after its PS5 file
        # adapter changes; no second writer or whole compiler rebuild is needed.
        run([settings['ninja'], '-C', Path(settings['output'])/'ps5', '-j', '2',
             'sims2-console-generator'], a.output.resolve(), 'check-generator-native')
    if a.game_unit: inputs += ['console_game_unit_steps.inc']
    if a.native_title_input:
        from native_title_probe import source_inputs
        inputs += source_inputs(ROOT)
    build_id = hashlib.sha256(a.mode.encode()+bytes([a.execute, a.generate, a.game_unit, a.all_game_units])+b''.join((compiler/name).read_bytes() for name in inputs)).hexdigest()[:16]
    output = a.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    fixtures = output/'linker-fixtures'
    fixtures.mkdir(exist_ok=True)
    clang = Path(settings['clang_bin'])/'clang-23.exe'
    kit = Path(settings['kit'])
    flags = [str(clang), '--target=x86_64-sie-ps5', '-isysroot', str(kit/'sdk'),
             '-resource-dir', str(kit/'clang-resource'), '-ffreestanding', '-fPIC',
             '-fno-stack-protector', '-fno-exceptions', '-fno-rtti', '-fno-plt',
             '-fno-unwind-tables', '-fno-asynchronous-unwind-tables', '-O2', '-g0', '-c']
    records = []
    fixture_jobs = [('entry', None), ('provider', 'SIMS2_FIXTURE_PROVIDER'), ('missing', 'SIMS2_FIXTURE_MISSING')] if a.mode == 'linker' else []
    for name, define in fixture_jobs:
        dest = fixtures/(name+'.o')
        run(flags + (['-D'+define] if define else []) + [compiler/'link_fixture.cpp', '-o', dest],
            output, 'fixture-'+name)
        records.append(dict(name=dest.name, sha256=sha(dest), bytes=dest.stat().st_size))
    generated = output/'generated'
    generated.mkdir(exist_ok=True)
    header = '// Generated by build_linker_probe.py. No game data.\n'
    if records:
        header += ('struct Sims2LinkFixture { const char *name; const char *sha256; };\n'
                   'static constexpr Sims2LinkFixture sims2LinkFixtures[] = {\n' +
                   ''.join('  {"%s", "%s"},\n' % (r['name'], r['sha256']) for r in records) + '};\n')
    resource_records = []
    if a.mode == 'compiler':
        resources = output/'compiler-resources'
        resources.mkdir(exist_ok=True)
        shutil.copyfile(compiler/'compile_fixture.cpp', resources/'compile_fixture.cpp')
        # The embedded compiler is LLVM 22: use its source resource headers,
        # never the Windows cross-compiler's LLVM 23 builtin headers.
        shutil.copytree(Path(settings['llvm'])/'clang/lib/Headers', resources/'clang-resource/include', dirs_exist_ok=True)
        shutil.copytree(kit/'sdk/target/include', resources/'sdk/target/include', dirs_exist_ok=True)
        for name in ('compile_fixture.cpp', 'clang-resource/include/stdint.h',
                     'clang-resource/include/stddef.h', 'sdk/target/include/c++/v1/array',
                     'sdk/target/include/c++/v1/cstdint'):
            resource_records.append(dict(name=name, sha256=sha(resources/name), bytes=(resources/name).stat().st_size))
        if a.execute:
            shutil.copyfile(compiler/'third_party/ps5_retroarch/ps5-core.ld', resources/'ps5-core.ld')
            resource_records.append(dict(name='ps5-core.ld', sha256=sha(resources/'ps5-core.ld'), bytes=(resources/'ps5-core.ld').stat().st_size))
        if a.generate:
            kit_info = verify_kit(kit)
            if sha(ROOT/'config/game.toml') != kit_info['files']['config/game.toml']['sha256']:
                raise BuildError('Game config differs from the reviewed generation oracle')
            for source, relative in [(ROOT/'config/game.toml', 'generator/config/game.toml')] + [
                    (p, 'generator/xdk/5849/'+p.name) for p in sorted((ROOT/'sdk/xdk/5849').glob('*.toml'))]:
                target = resources/relative; target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
                resource_records.append(dict(name=relative, sha256=sha(target), bytes=target.stat().st_size))
            header += ('struct Sims2GeneratedFile { const char *name; const char *sha256; };\n'
                'static constexpr Sims2GeneratedFile sims2GeneratedFiles[] = {\n'+
                ''.join('  {"%s", "%s"},\n' % item for item in sorted(kit_info['generated_files'].items()))+'};\n')
            if a.game_unit:
                shutil.copytree(kit/'runtime/cpu', resources/'game-runtime/cpu', dirs_exist_ok=True)
                for name in ('x86_ops.h', 'x86_context.h', 'guest_address.h'):
                    relative = 'game-runtime/cpu/'+name
                    resource_records.append(dict(name=relative, sha256=sha(resources/relative), bytes=(resources/relative).stat().st_size))
                arguments = [value.replace('{KIT}/runtime', '/app0/compiler-resources/game-runtime').replace('{KIT}', '/app0/compiler-resources')
                             for value in kit_info['compile_argv']]
                arguments[0] = '/app0/embedded-clang'
                header += ('static constexpr const char *sims2GameCompileArguments[] = {\n'+
                           ''.join('  '+json.dumps(value)+',\n' for value in arguments)+'};\n')
                units = sorted(name for name in kit_info['generated_files'] if name.endswith('.cpp'))
                if len(units) != kit_info['generated_cpp_count'] or len(units) != 65:
                    raise BuildError('Unexpected reviewed compilation-unit inventory')
                if not a.all_game_units: units = ['x86_recomp.0.cpp']
                header += ('static constexpr const char *sims2GameCompileSources[] = {\n'+
                           ''.join('  '+json.dumps(value)+',\n' for value in units)+'};\n')
        header += ('struct Sims2CompilerResource { const char *name; const char *sha256; };\n'
                   'static constexpr Sims2CompilerResource sims2CompilerResources[] = {\n'+
                   ''.join('  {"%s", "%s"},\n' % (r['name'], r['sha256']) for r in resource_records)+'};\n')
    if a.native_title_input:
        from native_title_probe import prepare as prepare_native
        native_header, native_info = prepare_native(ROOT, a.native_title_input.resolve(), kit, output)
        header += native_header
        build_id = hashlib.sha256(build_id.encode()+header.encode()).hexdigest()[:16]
    (generated/'fixture_manifest.h').write_text(header)
    shutil.copyfile(compiler/'console_probe_app.cpp', foundation/'examples'/SAMPLE/(SAMPLE+'.cpp'))
    prelude = foundation/'ps5/src/prelude.h'
    text = prelude.read_text()
    if '#include "ps5_samples.h"' not in text:
        text += '\n#include "ps5_samples.h"\n'
    if '#include "console_probe.h"' not in text:
        text += '\n#include "console_probe.h"\n'
    prelude.write_text(text)
    samples = foundation/'ps5/src/samples.cpp'
    text = samples.read_text()
    samples.write_text(text.replace('SAMPLE('+SAMPLE+', true,', 'SAMPLE('+SAMPLE+', false,'))
    # Carry the previously verified OpenSans customization into this generated
    # foundation, keeping upstream's weak font hook and native 4K rendering.
    for name in ('public-resources', 'licenses/opensans'):
        shutil.copytree(a.font_foundation/name, foundation/name, dirs_exist_ok=True)
    shutil.copyfile(a.font_foundation/'ps5/src/bootstrap_font.cpp', foundation/'ps5/src/bootstrap_font.cpp')
    cmake = foundation/'ps5/CMakeLists.txt'
    text = cmake.read_text()
    # CMake's SHELL splitting loses a path with spaces on this Windows workspace.
    text = text.replace('"SHELL:-include ${CMAKE_CURRENT_SOURCE_DIR}/third_party/volk/volk.h"',
                        '-include "${CMAKE_CURRENT_SOURCE_DIR}/third_party/volk/volk.h"')
    start = '# BEGIN SIMS2 LINKER PROBE\n'
    if start in text:
        text = text[:text.index(start)]
    text += start + '''target_sources(samples PRIVATE
  "${SIMS2_COMPILER_SOURCE}/console_probe.cpp"
  "${CMAKE_CURRENT_SOURCE_DIR}/src/bootstrap_font.cpp")
target_include_directories(samples PRIVATE
  "${SIMS2_COMPILER_SOURCE}" "${SIMS2_PROBE_GENERATED}"
  "${SIMS2_LLVM_SOURCE}/llvm/include" "${SIMS2_LLVM_BUILD}/include"
  "${SIMS2_PLATFORM_HEADERS}")
set_source_files_properties(
  "${SIMS2_COMPILER_SOURCE}/console_probe.cpp"
  "${CMAKE_BINARY_DIR}/wrap/${SIMS2_PROBE_SAMPLE}.cpp"
  PROPERTIES COMPILE_DEFINITIONS "SIMS2_PROBE_BUILD_ID=\\"${SIMS2_PROBE_BUILD_ID}\\"")
if(SIMS2_PROBE_COMPILER)
  set_property(SOURCE "${SIMS2_COMPILER_SOURCE}/console_probe.cpp"
    "${CMAKE_BINARY_DIR}/wrap/${SIMS2_PROBE_SAMPLE}.cpp"
    APPEND PROPERTY COMPILE_DEFINITIONS SIMS2_PROBE_COMPILER=1)
endif()
if(SIMS2_PROBE_EXECUTE)
  target_sources(samples PRIVATE
    "${SIMS2_COMPILER_SOURCE}/probe_core_loader.cpp"
    "${SIMS2_COMPILER_SOURCE}/third_party/ps5_retroarch/core_loader_ps5.cpp")
  set_property(SOURCE "${SIMS2_COMPILER_SOURCE}/console_probe.cpp"
    "${CMAKE_BINARY_DIR}/wrap/${SIMS2_PROBE_SAMPLE}.cpp"
    APPEND PROPERTY COMPILE_DEFINITIONS SIMS2_PROBE_EXECUTE=1)
endif()
if(SIMS2_PROBE_GENERATE)
  set_property(SOURCE "${SIMS2_COMPILER_SOURCE}/console_probe.cpp"
    "${CMAKE_BINARY_DIR}/wrap/${SIMS2_PROBE_SAMPLE}.cpp"
    APPEND PROPERTY COMPILE_DEFINITIONS SIMS2_PROBE_GENERATE=1)
endif()
if(SIMS2_PROBE_GAME_UNIT)
  set_property(SOURCE "${SIMS2_COMPILER_SOURCE}/console_probe.cpp"
    "${CMAKE_BINARY_DIR}/wrap/${SIMS2_PROBE_SAMPLE}.cpp"
    APPEND PROPERTY COMPILE_DEFINITIONS SIMS2_PROBE_GAME_UNIT=1)
endif()
set_property(SOURCE "${SIMS2_COMPILER_SOURCE}/console_probe.cpp"
  "${CMAKE_BINARY_DIR}/wrap/${SIMS2_PROBE_SAMPLE}.cpp"
  APPEND PROPERTY COMPILE_DEFINITIONS SIMS2_PROBE_GAME_UNIT_COUNT=${SIMS2_PROBE_GAME_UNIT_COUNT})
if(SIMS2_PROBE_NATIVE_TITLE)
  target_sources(samples PRIVATE
    "${SIMS2_COMPILER_SOURCE}/native_packager.cpp"
    "${SIMS2_COMPILER_SOURCE}/third_party/ps5_native_tool/elf_object.cpp"
    "${SIMS2_COMPILER_SOURCE}/third_party/ps5_native_tool/sce_module_writer.cpp"
    "${SIMS2_COMPILER_SOURCE}/third_party/ps5_native_tool/self_container.cpp")
  target_include_directories(samples PRIVATE "${SIMS2_COMPILER_SOURCE}/third_party/zlib_headers")
  set_property(SOURCE "${SIMS2_COMPILER_SOURCE}/console_probe.cpp"
    "${CMAKE_BINARY_DIR}/wrap/${SIMS2_PROBE_SAMPLE}.cpp"
    APPEND PROPERTY COMPILE_DEFINITIONS SIMS2_PROBE_NATIVE_TITLE=1)
endif()
# END SIMS2 LINKER PROBE
'''
    cmake.write_text(text)
    build = foundation/'build/windows-ps5'
    argv = [settings['cmake'], '-S', foundation/'ps5', '-B', build, '-G', 'Ninja',
            '-DCMAKE_MAKE_PROGRAM='+settings['ninja'], '-DCMAKE_BUILD_TYPE=Release',
            '-DCMAKE_EXPORT_COMPILE_COMMANDS=ON',
            '-DCMAKE_TOOLCHAIN_FILE='+str(compiler/'ps5-toolchain.cmake'),
            '-DSIMS2_COMPILER_BIN='+Path(settings['clang_bin']).as_posix(),
            '-DSIMS2_PUBLIC_KIT='+kit.as_posix(),
            '-DSIMS2_COMPILER_SOURCE='+compiler.as_posix(),
            '-DSIMS2_PROBE_GENERATED='+generated.as_posix(),
            '-DSIMS2_LLVM_SOURCE='+Path(settings['llvm']).as_posix(),
            '-DSIMS2_LLVM_BUILD='+(Path(settings['output'])/'ps5').as_posix(),
            '-DSIMS2_PLATFORM_HEADERS='+a.platform_headers.resolve().as_posix(),
            '-DSIMS2_PROBE_BUILD_ID='+build_id,
            '-DSIMS2_PROBE_SAMPLE='+SAMPLE,
            '-DSIMS2_PROBE_COMPILER='+('ON' if a.mode == 'compiler' else 'OFF'),
            '-DSIMS2_PROBE_EXECUTE='+('ON' if a.execute else 'OFF'),
            '-DSIMS2_PROBE_GENERATE='+('ON' if a.generate else 'OFF'),
            '-DSIMS2_PROBE_GAME_UNIT='+('ON' if a.game_unit else 'OFF'),
            '-DSIMS2_PROBE_GAME_UNIT_COUNT='+str(65 if a.all_game_units else (1 if a.game_unit else 0)),
            '-DSIMS2_PROBE_NATIVE_TITLE='+('ON' if a.native_title_input else 'OFF')]
    run(argv, output, 'configure-probe')
    run([settings['ninja'], '-C', build, '-j', '2', 'samples'], output, 'build-probe-objects')
    (output/'probe-inputs.json').write_text(json.dumps(dict(
        build_id=build_id, title_id=TITLE_ID, mode=a.mode, fixtures=records,
        compiler_resources=resource_records, execution_probe=a.execute, generation_probe=a.generate,
        game_unit_probe=a.game_unit,
        game_unit_count=65 if a.all_game_units else (1 if a.game_unit else 0),
        watchdog_seconds=1800 if a.all_game_units else (300 if a.native_title_input else 120),
        native_title_probe=native_info,
        authored_inputs={name: sha(compiler/name) for name in inputs},
        console_status='NOT_TESTED'), indent=2)+'\n')


def package(a, settings):
    output = a.output.resolve()
    native_receipt = 'build-ps5-final.json' if a.mode == 'compiler' else 'build-linker.json'
    receipt = json.loads((Path(settings['output'])/native_receipt).read_text())
    if receipt['status'] != 'PASS':
        raise BuildError('Native linker libraries have not finished building')
    if a.mode == 'compiler':
        base = json.loads((Path(settings['output'])/'build-ps5.json').read_text())
        if base['status'] != 'PASS' or receipt['started'] < base['started']:
            raise BuildError('A current final compiler-library check is required')
    inventory = json.loads((output/'probe-inputs.json').read_text())
    if inventory.get('mode') != a.mode: raise BuildError('Prepared probe mode does not match packaging mode')
    if inventory.get('execution_probe', False) != a.execute: raise BuildError('Prepared execution mode differs')
    if inventory.get('generation_probe', False) != a.generate: raise BuildError('Prepared generation mode differs')
    if inventory.get('game_unit_probe', False) != a.game_unit: raise BuildError('Prepared game-unit mode differs')
    if inventory.get('game_unit_count', 0) != (65 if a.all_game_units else (1 if a.game_unit else 0)):
        raise BuildError('Prepared game-unit count differs')
    if bool(inventory.get('native_title_probe')) != bool(a.native_title_input):
        raise BuildError('Prepared native-title mode differs')
    for name, digest in inventory['authored_inputs'].items():
        if sha(ROOT/'compiler'/name) != digest:
            raise BuildError('Probe source changed; run prepare again: '+name)
    kit = Path(settings['kit']).resolve()
    manifest = verify_kit(kit)
    # Query the actual CMake/Ninja dependency graph. Group the archives so
    # cyclic LLVM dependencies resolve without guessing a handwritten order.
    native_build = Path(settings['output'])/'ps5'
    listing = subprocess.check_output([settings['ninja'], '-C', str(native_build),
        '-t', 'inputs', 'sims2-console-compiler' if a.mode == 'compiler' else 'sims2-console-linker', 'lldELF'], text=True)
    libraries = sorted({(native_build/line).resolve() for line in listing.splitlines()
                        if line.endswith('.a')})
    if not {'libsims2-console-linker.a', 'liblldELF.a'} <= {p.name for p in libraries}:
        raise BuildError('Native linker dependency graph is incomplete')
    if any(not p.is_file() for p in libraries):
        raise BuildError('Incomplete native linker dependency archives')
    if a.mode == 'compiler' and 'libsims2-console-compiler.a' not in {p.name for p in libraries}:
        raise BuildError('Missing embedded compiler archive')
    commands = json.loads((a.foundation/'build/windows-ps5/compile_commands.json').read_text())
    objects = [Path(c['output']) for c in commands]
    if not objects or any(not p.is_file() for p in objects):
        raise BuildError('Incomplete foundation/probe objects')
    work = output/'package'
    attempt = 1
    while work.exists():
        attempt += 1
        work = output/('package-attempt-%04d' % attempt)
    work.mkdir(exist_ok=False)
    (work/'tmp').mkdir()
    job = Builder(kit, work/'unused.iso', work/'unused'); job.work = work
    title = work/TITLE_ID
    def expand(argv):
        values = dict(KIT=str(kit), WORK=str(work), TITLE=str(title))
        return [re.sub(r'\{([A-Z_]+)\}', lambda m: values[m[1]], x) for x in argv]
    argv = expand(manifest['link_argv'])
    # Keep the proven RADV recipe. Extend its established defsym bindings only
    # for real implementations in the exact, hash-verified platform archive.
    bindings = json.loads((ROOT/'compiler/ps5-link-bindings.json').read_text())
    if bindings['schema'] != 1: raise BuildError('Unsupported platform binding inventory')
    # LLVM's constant-initialized external TLS scalar has an optional weak
    # initializer. This title provides its LLVM statically, not through a DSO.
    # LLD's documented ELF mode resolves absent weak definitions to zero;
    # required imports remain checked. Do not manufacture a dummy initializer
    # or turn this optional callback into a required console-module import.
    weak_options = bindings.get('elf_link_options', [])
    if weak_options != ['-z', 'nodynamic-undefined-weak']:
        raise BuildError('Unexpected weak ELF import policy')
    argv[1:1] = weak_options
    platform = [Path(x) for x in argv if x.endswith('-libps5platform.a')]
    if len(platform) != 1: raise BuildError('Cannot identify captured platform archive')
    exports = job.run([str(kit/'tools/llvm-nm.exe'), '--defined-only', '--extern-only',
                      str(platform[0])], 'platform-definitions')
    defined_platform = set(re.findall(r'\b[TW]\s+(\S+)', exports.read_text()))
    for name, implementation in bindings['aliases'].items():
        if not re.fullmatch('[a-zA-Z_][a-zA-Z0-9_]*', name) or implementation != 'ps5_'+name:
            raise BuildError('Invalid platform binding: '+name)
        if implementation not in defined_platform:
            raise BuildError('Pinned platform archive lacks '+implementation)
        binding = '--defsym='+name+'='+implementation
        if binding not in argv: argv.insert(1, binding)
    # The captured platform visibility map predates these aliases too. Keep
    # their implementation private like its other libc bindings; the native
    # title format does not publish application exports.
    local_map = work/'compiler-platform-local.map'
    local_map.write_text('{\n  local:\n'+''.join(
        '    '+name+';\n' for name in sorted(bindings['aliases']))+'};\n')
    argv[1:1] = ['--version-script', str(local_map)]
    (work/'platform-bindings.json').write_text(json.dumps(dict(
        platform_sha256=sha(platform[0]), aliases=bindings['aliases'],
        elf_link_options=weak_options), indent=2)+'\n')
    first = next(i for i, x in enumerate(argv) if x.endswith('-app_crt.o'))
    last = next(i for i, x in enumerate(argv) if x.endswith('-libSceAgc.so'))
    if first >= last: raise BuildError('Unrecognized captured RADV application object boundary')
    argv = argv[:first+1] + [str(p.resolve()) for p in objects] + ['--start-group'] + \
        [str(p) for p in libraries] + ['--end-group'] + argv[last:]
    # Keep the exact ordered RADV arguments. Larger installer object lists can
    # exceed CreateProcess's 32K command-line limit on Windows. LLD explicitly
    # supports the same Windows tokenization as subprocess.list2cmdline.
    (work/'link-arguments.json').write_text(json.dumps(argv,indent=2)+'\n')
    if os.name=='nt' and len(subprocess.list2cmdline(argv))>30000:
        response=work/'link-probe.rsp'
        response.write_text(subprocess.list2cmdline(argv[1:])+'\n',encoding='utf-8')
        job.run([argv[0],'--rsp-quoting=windows','@'+str(response)], 'link-probe', timeout=1800)
    else:
        job.run(argv, 'link-probe', timeout=1800)
    verify_native_elf(work/'llvm-pie.elf')
    defined = job.run([str(kit/'tools/llvm-nm.exe'), '--defined-only', str(work/'llvm-pie.elf')], 'defined-symbols')
    if re.search(r'__imp__sub_[0-9A-Fa-f]+|X86FuncMappings|X86Continuations', defined.read_text()):
        raise BuildError('Game symbols in synthetic public probe')
    imports = job.run(expand(manifest['undefined_argv']), 'undefined-imports')
    undefined_names = set(re.findall(r'\b[Uwv]\s+(\S+)', imports.read_text()))
    # An old allowlist admits libc names which link but fault when called by a
    # title. Explicit SDK bindings must actually remove those imports.
    still_imported = undefined_names & set(bindings['aliases'])
    if still_imported:
        raise BuildError('Platform replacements still imported from libc: '+', '.join(sorted(still_imported)))
    unknown = undefined_names - set(manifest['allowed_imports'])
    if unknown: raise BuildError('Unverified runtime imports: '+', '.join(sorted(unknown)))
    dynamic = job.run([str(kit/'tools/llvm-nm.exe'), '-D', '--defined-only',
                       str(work/'llvm-pie.elf')], 'dynamic-definitions')
    if dynamic.read_text().strip():
        raise BuildError('Unexpected application exports; inspect dynamic-definitions.log')
    title.mkdir()
    (title/'assets').mkdir()
    (title/'assets/README.txt').write_text('Synthetic console preparation diagnostic. No game data included.\n')
    for name in ('sce_module', 'licenses'):
        shutil.copytree(kit/'title'/name, title/name)
    shutil.copytree(a.foundation/'ps5/sce_sys', title/'sce_sys')
    shutil.copyfile(kit/'title/LICENSE', title/'LICENSE')
    for name in ('public-resources', 'licenses/opensans', 'shaders/glsl/base'):
        shutil.copytree(a.foundation/name, title/name, dirs_exist_ok=True)
    if a.mode == 'compiler':
        shutil.copytree(output/'compiler-resources', title/'compiler-resources')
        if any((title/'compiler-resources').rglob('*.o')):
            raise BuildError('Compiler diagnostic must generate its objects on PS5')
    else:
        shutil.copytree(output/'linker-fixtures', title/'linker-fixtures')
    # Preserve generic compiler third-party notices with the diagnostic package.
    license_dir = title/'licenses/llvm'; license_dir.mkdir()
    shutil.copyfile(Path(settings['llvm'])/'llvm/LICENSE.TXT', license_dir/'LICENSE.TXT')
    if a.execute:
        loader_licenses = title/'licenses/ps5_retroarch'; loader_licenses.mkdir()
        for name in ('LICENSE', 'ORIGIN.json'):
            shutil.copyfile(ROOT/'compiler/third_party/ps5_retroarch'/name, loader_licenses/name)
    if a.native_title_input:
        shutil.copytree(output/'native-title-kit', title/'native-title-kit')
        for name in ('ps5_native_tool', 'zlib_headers'):
            destination = title/'licenses'/name; destination.mkdir()
            for file in ('LICENSE', 'ORIGIN.json'):
                shutil.copyfile(ROOT/'compiler/third_party'/name/file, destination/file)
    for stage in ('convert', 'sign', 'inspect'):
        job.run(expand(manifest[stage+'_argv']), stage)
    inventory.update(status='BUILD_PASS_CONSOLE_NOT_TESTED',
        eboot_sha256=sha(title/'eboot.bin'), debug_elf_sha256=sha(work/'llvm-pie.elf'),
        library_files=[dict(name=p.name, sha256=sha(p)) for p in libraries],
        files={p.relative_to(title).as_posix():dict(bytes=p.stat().st_size, sha256=sha(p))
               for p in sorted(title.rglob('*')) if p.is_file()})
    (work/'build-manifest.json').write_text(json.dumps(inventory, indent=2)+'\n')
    (output/'package-result.json').write_text(json.dumps(dict(
        status=inventory['status'], build_id=inventory['build_id'],
        manifest=str(work/'build-manifest.json'), title=str(title)), indent=2)+'\n')
    print(json.dumps(dict(status=inventory['status'], title=str(title), build_id=inventory['build_id'])))


def finish(a, settings):
    """Await this explicit library build, then package once; never run Ninja."""
    output = a.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    state_path = output/'state-finish-probe.json'
    prerequisite = Path(settings['output'])/('build-ps5.json' if a.mode == 'compiler' else 'build-linker.json')
    initial = json.loads(prerequisite.read_text())
    state = dict(stage='finish-probe', pid=os.getpid(), started=time.time(),
                 status='WAITING', prerequisite_started=initial['started'])
    state_path.write_text(json.dumps(state, indent=2)+'\n')
    print(json.dumps(state), flush=True)
    try:
        deadline = time.monotonic()+6*3600
        while True:
            try: receipt = json.loads(prerequisite.read_text())
            except (OSError, ValueError): receipt = {}
            if receipt.get('started') not in (None, initial['started']):
                raise BuildError('Native library job was replaced; inspect and restart the watcher')
            if receipt.get('status') == 'FAIL': raise BuildError('Native linker build failed; inspect build-linker.log')
            if receipt.get('status') == 'PASS':
                if a.mode == 'linker': break
                try: final = json.loads((Path(settings['output'])/'build-ps5-final.json').read_text())
                except (OSError, ValueError): final = {}
                if final.get('started', 0) >= initial['started']:
                    if final.get('status') == 'FAIL': raise BuildError('Final compiler dependency check failed')
                    if final.get('status') == 'PASS': break
            if time.monotonic() > deadline: raise BuildError('Timed out waiting for native linker libraries')
            time.sleep(2)
        state.update(status='PACKAGING'); state_path.write_text(json.dumps(state, indent=2)+'\n')
        package(a, settings)
        state.update(status='BUILD_PASS_CONSOLE_NOT_TESTED')
    except BaseException as error:
        state.update(status='FAIL', error=str(error))
        raise
    finally:
        state.update(finished=time.time())
        state_path.write_text(json.dumps(state, indent=2)+'\n')


def main():
    global TITLE_ID, SAMPLE
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--settings', type=Path, required=True)
    p.add_argument('--phase', choices=('prepare', 'package', 'finish'), required=True)
    p.add_argument('--mode', choices=('linker', 'compiler'), default='linker')
    p.add_argument('--execute', action='store_true', help='also load/execute the authored no-import fixture with the pinned PS5_RetroArch loader')
    p.add_argument('--generate', action='store_true', help='also verify private owner-XBE source generation on console; never bundle the XBE')
    p.add_argument('--game-unit', action='store_true', help='compile one generated game unit using the reviewed owner-builder flags; never execute it')
    p.add_argument('--all-game-units', action='store_true', help='extend the first-unit profile to all 65 generated sources, sequentially')
    p.add_argument('--native-title-input', type=Path, help='private evidence from a passing 65-unit PS5 run; package its console objects into a private native executable')
    p.add_argument('--foundation', type=Path)
    p.add_argument('--font-foundation', type=Path, default=ROOT.parent/'PS5_Sims2Bootstrap')
    p.add_argument('--platform-headers', type=Path, required=True)
    p.add_argument('--output', type=Path)
    a = p.parse_args()
    if a.execute and a.mode != 'compiler': p.error('--execute requires --mode compiler')
    if a.generate and not a.execute: p.error('--generate requires --execute')
    if a.game_unit and not a.generate: p.error('--game-unit requires --generate')
    if a.all_game_units and not a.game_unit: p.error('--all-game-units requires --game-unit')
    if a.native_title_input and (not a.execute or a.generate or a.game_unit):
        p.error('--native-title-input requires --execute and reuses prior objects; omit --generate/--game-unit')
    if a.mode == 'compiler': TITLE_ID, SAMPLE = 'PPSA99147', 'sims2compilerdiagnostics'
    if a.foundation is None: a.foundation = ROOT.parent/('PS5_Sims2CompilerProbe' if a.mode == 'compiler' else 'PS5_Sims2LinkerProbe')
    if a.output is None: a.output = ROOT/('out/console-compiler-probe' if a.mode == 'compiler' else 'out/console-linker-probe')
    settings = json.loads(a.settings.read_text())
    os.environ['PATH'] = settings['clang_bin'] + os.pathsep + os.environ.get('PATH', '')
    try:
        {'prepare': prepare, 'package': package, 'finish': finish}[a.phase](a, settings)
    except (BuildError, OSError, ValueError) as e:
        p.exit(1, 'ERROR: '+str(e)+'\n')


if __name__ == '__main__': main()
